export function hashDay(day) {
  let h = 0;
  for (const ch of day) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return h;
}

// 今天的那一句：同一天固定同一句，按「換一句」才換。mineOnly 時只從自己寫的抽
export function quoteOfDay({ day, mine = [], offset = 0, mineOnly = false }) {
  const own = mine.map((q) => ({ text: q.text, id: q.id, mine: true }));
  const pool = mineOnly && own.length ? own : [...own, ...BUILTIN_QUOTES.map((text) => ({ text, mine: false }))];
  if (!pool.length) return null;
  return pool[(hashDay(day) + offset) % pool.length];
}

