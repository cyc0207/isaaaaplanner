// 每張牌在這個位置的解讀（牌義）
export function topicReading(topic, cards) {
  return cards.map((id, i) => {
    const c = oracleCard(id);
    if (!c) return null;
    const pos = TOPICS[topic].positions[i];
    const text = topic === 'wear' ? c.wear[i] : topic === 'eat' ? c.eat : c.love;
    return { id, card: c, pos, text };
  }).filter(Boolean);
}

// 今天的行動：做得到的一件小事，跟牌義分開
export function topicAction(topic, cards, color = null) {
  const cs = cards.map(oracleCard);
  if (cs.some((c) => !c)) return '';
  if (topic === 'wear') {
    const c = color && colorById(color.colorId);
    return c
      ? `今天的顏色是${c.name}，${color.spot}。主角是「${cs[1].wear[1]}」，細節：${cs[2].wear[2]}。穿好拍一張 OOTD`
      : `今天以${cs[0].wear[0]}為主，主角是「${cs[1].wear[1]}」，細節：${cs[2].wear[2]}。穿好拍一張 OOTD`;
  }
  if (topic === 'eat') return `照「${cs[0].eat}」的方向挑一餐${cs[1].eat !== cs[0].eat ? `，也可以參考「${cs[1].eat}」` : ''}`;
  return cs[cs.length - 1].act;
}

// 首頁「今天吃什麼」卡用的一行字
export function eatLine(entry) {
  const cs = (entry?.cards || []).map(oracleCard).filter(Boolean);
  if (!cs.length) return '';
  return `${cs.map((c) => c.zh).join('＋')}：${cs[0].eat}`;
}

