export const DECKS = {
  lenormand: { name: '雷諾曼', cards: LENORMAND, spreads: [1, 3, 5, 9] },
  sibilla: { name: '西比拉', cards: SIBILLA, spreads: [1, 3, 5] },
};

const ALL = Object.fromEntries([...LENORMAND, ...SIBILLA].map((c) => [c.id, c]));
export const oracleCard = (id) => ALL[id] || null;

// 從一副牌抽 n 張不重複的；rnd 回傳 [0, 1)
export function drawFrom(deck, n, rnd = Math.random) {
  const pool = DECKS[deck].cards.map((c) => c.id);
  return Array.from({ length: Math.min(n, pool.length) }, () => {
    const i = Math.floor(rnd() * pool.length) % pool.length;
    return pool.splice(i, 1)[0];
  });
}

